#!/usr/bin/env python3
"""Generate all shell/editor completions from the compiler's canonical table."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shlex

ROOT_DIR = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT_DIR / 'completions/bash/vitte'
GENERATOR_VERSION = '3.0'
SCHEMA_VERSION = 3


def canonical_spec():
    source = (ROOT_DIR / 'src/bootstrap/cli/command_spec.def').read_text()
    commands = dict(re.findall(r'VITTE_CLI_COMMAND\("([^"]+)", "([^"]+)"', source))
    options = {}
    for spelling, argument, description in re.findall(r'VITTE_CLI_OPTION\("([^"]+)", (NULL|"[^"]+"), "([^"]+)"', source):
        if spelling.startswith('-- '):
            continue
        for alias in spelling.split(', '):
            name = re.split('[ =]', alias)[0]
            options[name] = {'description': description, 'argument': None if argument == 'NULL' else argument.strip('"')}
    values = {'--diagnostic': ['terminal', 'json', 'sarif', 'lsp'], '--diagnostic-format': ['terminal', 'json', 'sarif', 'lsp'],
              '--profile': ['default', 'debug', 'release', 'size', 'sanitize', 'freestanding'],
              '--backend': ['default', 'c17', 'native', 'bytecode'], '--optimization': ['0', '1', '2', '3'], '--opt': ['0', '1', '2', '3']}
    return {'schema_version': SCHEMA_VERSION, 'commands': commands, 'options': options, 'values': values}


def spec_sha256():
    return hashlib.sha256(json.dumps(canonical_spec(), sort_keys=True).encode()).hexdigest()


def header():
    return '# Generated by tools/generate_completions.py; do not edit.\n# completion-spec-sha256: ' + spec_sha256() + '\n'


def generate_bash():
    spec = canonical_spec()
    value_opts = [name for name, opt in spec['options'].items() if opt['argument']]
    # --version is an argument-taking package option only with install.
    value_opts.remove('--version')
    cases = '\n'.join('    ' + name + ') words=' + shlex.quote(' '.join(values)) + ' ;;' for name, values in spec['values'].items())
    directories = ' | '.join(name for name, opt in spec['options'].items() if opt['argument'] == 'PATH' and name not in ['-o', '--output', '--manifest-path'])
    return header() + '''
_vitte_option_value() {
  local option="$1" cur="$2" words='' candidate
  COMPREPLY=()
  case "$option" in
''' + cases + '''
    ''' + directories + ''')
      while IFS= read -r candidate; do COMPREPLY+=("$candidate/"); done < <(compgen -d -- "$cur")
      return ;;
    -o | --output | --manifest-path)
      while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -f -- "$cur")
      compopt -o filenames 2>/dev/null || true
      return ;;
  esac
  if [[ -n "$words" ]]; then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W "$words" -- "$cur")
  fi
}
_vitte_complete() {
  local cur="${COMP_WORDS[COMP_CWORD]}" prev='' cmd='' word option='' prefix='' candidate i
  local expect=0 ended=0
  COMPREPLY=()
  # Read the actual context, including global options before the command.
  for ((i=1; i<COMP_CWORD; i++)); do
    word="${COMP_WORDS[i]}"
    if (( expect )); then expect=0; continue; fi
    if [[ "$word" == -- ]]; then ended=1; break; fi
    case "$word" in
      ''' + ' | '.join(value_opts) + ''') expect=1 ;;
      --version) [[ "$cmd" == install ]] && expect=1 ;;
      -*) ;;
      *) [[ -z "$cmd" ]] && cmd="$word" ;;
    esac
  done
  if (( ended )); then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -f -- "$cur")
    compopt -o filenames 2>/dev/null || true
    return
  fi
  if (( COMP_CWORD > 0 )); then prev="${COMP_WORDS[COMP_CWORD-1]}"; fi
  if (( expect )); then _vitte_option_value "$prev" "$cur"; return; fi
  if [[ "$cur" == --*=* ]]; then
    option="${cur%%=*}"; prefix="$option="
    _vitte_option_value "$option" "${cur#*=}"
    for ((i=0;i<${#COMPREPLY[@]};i++)); do COMPREPLY[i]="$prefix${COMPREPLY[i]}"; done
    return
  fi
  # Bash often splits --name=value at '=' (COMP_WORDBREAKS).
  if [[ "$prev" == = && COMP_CWORD -gt 1 ]]; then
    _vitte_option_value "${COMP_WORDS[COMP_CWORD-2]}" "$cur"; return
  fi
  if [[ "$cur" == = && "$prev" == --* ]]; then _vitte_option_value "$prev" ''; return; fi
  if [[ "$cur" == -* ]]; then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W ''' + shlex.quote(' '.join(spec['options'])) + ''' -- "$cur")
    return
  fi
  if [[ "$cmd" == completion ]]; then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W 'bash zsh fish' -- "$cur")
    return
  fi
  if [[ -z "$cmd" ]]; then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W ''' + shlex.quote(' '.join(spec['commands'])) + ''' -- "$cur")
  fi
  if [[ "$cmd" == install || "$cmd" == explain || "$cmd" == version ]]; then return; fi
  while IFS= read -r candidate; do
    if [[ -d "$candidate" ]]; then COMPREPLY+=("$candidate/")
    elif [[ "$candidate" == *.vit || "$candidate" == *.vitl || "$candidate" == *.vitte ]]; then COMPREPLY+=("$candidate"); fi
  done < <(compgen -f -- "$cur")
  compopt -o filenames 2>/dev/null || true
}
complete -o bashdefault -F _vitte_complete vitte vittec
'''


def generate_zsh():
    spec = canonical_spec()
    lines = ['#compdef vitte vittec', header(), '_vitte() {', '  local context state state_descr line', '  typeset -A opt_args', '  _arguments -s -S \\']
    for name, opt in spec['options'].items():
        text = name + ('=' if name.startswith('--') and opt['argument'] else '') + '[' + opt['description'].replace(':', '\\:') + ']'
        if opt['argument']:
            values = spec['values'].get(name)
            action = '(' + ' '.join(values) + ')' if values else ('_files -/' if opt['argument'] == 'PATH' and name not in ['-o', '--output', '--manifest-path'] else '_files' if opt['argument'] == 'PATH' else '')
            text += ':' + opt['argument'] + ':' + action
        lines.append('    ' + shlex.quote(text) + ' \\')
    lines += ["    '1:command:->command' \\", "    '*:argument:->argument'", '  case "$state" in', '    command)', '      local -a commands', '      commands=(']
    for name, desc in spec['commands'].items():
        lines.append('        ' + shlex.quote(name + ':' + desc))
    lines += ["      )", "      _describe 'command' commands ;;", '    argument)', '      case "${line[1]}" in', "        completion) _values 'shell' bash zsh fish ;;", '        install|explain|version) ;;', "        *) _files -g '*.(vit|vitl|vitte)' ;;", '      esac ;;', '  esac', '}', '_vitte "$@"', '']
    return '\n'.join(lines)


def generate_fish():
    spec = canonical_spec()
    lines = [header(), r"""function __vitte_complete_sources
    for candidate in (__fish_complete_path (commandline -ct))
        set -l name (string split \t -- "$candidate")[1]
        if string match -rq '(\.(vit|vitl|vitte)|/)$' -- "$name"
            printf '%s\n' "$candidate"
        end
    end
end
complete -c vitte -f"""]
    for name, desc in spec['commands'].items():
        lines.append('complete -c vitte -n __fish_use_subcommand -a ' + shlex.quote(name) + ' -d ' + shlex.quote(desc))
    for name, opt in spec['options'].items():
        flag = '-l ' + name[2:] if name.startswith('--') else '-s ' + name[1:]
        line = 'complete -c vitte ' + flag + ' -d ' + shlex.quote(opt['description'])
        if opt['argument']:
            line += ' -r'
            values = spec['values'].get(name)
            if values: line += ' -f -a ' + shlex.quote(' '.join(values))
            elif opt['argument'] == 'PATH': line += ' -a ' + shlex.quote('(__fish_complete_directories)' if name not in ['-o', '--output', '--manifest-path'] else '(__fish_complete_path (commandline -ct))')
        lines.append(line)
    lines += ["complete -c vitte -n '__fish_seen_subcommand_from completion' -f -a 'bash zsh fish'", "complete -c vitte -n '__fish_seen_subcommand_from check compile run lex parse' -a '(__vitte_complete_sources)'", "complete -c vittec -w vitte", '']
    return '\n'.join(lines)


def generate_vim():
    grammar = json.loads((ROOT_DIR / 'editors/grammar/vitte_highlight_grammar.json').read_text())
    words = list(dict.fromkeys(grammar['keywords'] + grammar['types'] + grammar['literals']))
    return '" Generated by tools/generate_completions.py.\nlet g:vitte_completion_words = ' + json.dumps(words) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--stdout', action='store_true')
    parser.add_argument('--shell', choices=['bash', 'zsh', 'fish', 'vim'], default='bash')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--dump-spec', action='store_true')
    parser.add_argument('--print-spec-sha256', action='store_true')
    args = parser.parse_args()
    if args.dump_spec: print(json.dumps(canonical_spec(), indent=2)); return 0
    if args.print_spec_sha256: print(spec_sha256()); return 0
    generated = {'bash': generate_bash(), 'zsh': generate_zsh(), 'fish': generate_fish(), 'vim': generate_vim()}
    if args.stdout: print(generated[args.shell], end=''); return 0
    outputs = {ROOT_DIR / 'completions/bash/vitte': generated['bash'], ROOT_DIR / 'completions/zsh/_vitte': generated['zsh'], ROOT_DIR / 'completions/fish/vitte.fish': generated['fish'], ROOT_DIR / 'completions/vim/complete.vim': generated['vim']}
    if args.output: outputs = {args.output: generated[args.shell]}
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: print('Stale completions: ' + ', '.join(stale)); return 1
    print('Completions ' + ('verified' if args.check else 'generated') + ' for Bash, Zsh, Fish and Vim')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
